"""make scale: measure the Company Map at several company sizes and write docs/SCALE.md. Offline, no model."""
from __future__ import annotations

import json
import subprocess
import sys
from datetime import datetime, timezone
from typing import Any

from colex import settings
from tests.scale import measure
from tests.scale.report_text import INTRO, LIMITS, live_section

SIZES = (0, 200, 1000, 5000)
RESULTS = settings.ROOT / "tests" / "scale" / "live_results.json"


def _answers(row: dict[str, Any]) -> dict[str, int]:
    return {name: t["tokens"] for name, t in row["tools"].items() if not name.startswith("_")}


def render(rows: list[dict[str, Any]], live: list[dict[str, Any]]) -> str:
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=settings.ROOT, capture_output=True,
                         text=True).stdout.strip()
    names, limit = list(_answers(rows[0])), rows[0]["max_chars"] // 4
    out = ["# Company Map at scale", "", "Generated by `make scale`. Do not edit by hand.", "",
           f"- Date: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC · git {sha}", "", INTRO, "",
           "## Building the map (no model call)", "",
           "| Resources | All text (tokens) | Sections | Build | Rebuild after one document changed | "
           "Could not be placed (wait for a person) |", "|---|---|---|---|---|---|"]
    out += [f"| {r['resources']:,} | {r['corpus_tokens']:,} | {r['fragments']:,} | {r['build_s']} s | "
            f"{r['rebuild_s']} s ({r['reused']:,} reused) | {r['unclassified']:,} |" for r in rows]
    out += ["", "## Size of one map answer (tokens)", "",
            f"The agent reads these answers, never the documents themselves. An answer is limited to about "
            f"{limit:,} tokens.", "",
            "| Resources | " + " | ".join(names) + " | Cut off |", "|---|" + "---|" * (len(names) + 1)]
    out += [f"| {r['resources']:,} | " + " | ".join(f"{_answers(r)[n]:,}" for n in names)
            + f" | {sum(t['truncated'] for t in r['tools'].values() if 'truncated' in t)} |" for r in rows]
    out += ["", "## Are the places that must change still reachable?", "",
            "The scripted path already knows where the nine places of the ground truth are. It measures the cost of "
            "the path, not the cost of finding it.", "",
            "| Resources | Sandbox resources still filed in the same place | Places reachable | List pages needed, "
            "no filter (worst) | List pages needed, with a type filter (worst) | Scripted path (tokens) |",
            "|---|---|---|---|---|---|"]
    for r in rows:
        n = r["needles"]
        out.append(f"| {r['resources']:,} | {n['placed_as_before']} of {n['resources_in_truth']} | "
                   f"{n['places'] - len(n['unreachable'])} of {n['places']} | {n['max_pages_plain']} | "
                   f"{n['max_pages_by_type']} | {n['scripted_walk_tokens']:,} |")
    out += ["", "## One act analysed by the real model", "", *live_section(live),
            "", "## What this does not show", "", *LIMITS]
    return "\n".join(out) + "\n"


def main() -> int:
    rows = [measure.measure(size) for size in SIZES]
    live = json.loads(RESULTS.read_text(encoding="utf-8")) if RESULTS.is_file() else []
    (settings.ROOT / "docs" / "SCALE.md").write_text(render(rows, live), encoding="utf-8")
    for r in rows:
        print(f"{r['resources']:>6,} resources · build {r['build_s']} s · largest answer "
              f"{max(_answers(r).values()):,} tokens · {r['needles']['placed_as_before']} of "
              f"{r['needles']['resources_in_truth']} sandbox resources in place")
    print("wrote docs/SCALE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
