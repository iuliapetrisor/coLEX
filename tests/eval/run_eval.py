"""make eval: run the demo, score it against the hidden ground truth, write docs/RESULTS.md."""
from __future__ import annotations

import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
os.environ["COLEX_DEMO_DIR"] = str(ROOT / "var" / "eval")

from colex import demo, settings  # noqa: E402
from colex.config import ConfigStore  # noqa: E402
from tests.eval.scoring import score  # noqa: E402


def pct(a: int, b: int) -> str:
    return f"{a}/{b} ({100 * a / b:.0f}%)" if b else "n/a (0 cases)"


def main() -> int:
    exit_code = demo.main(["--quiet"])
    s = score()
    t, i, m = s["triage"], s["impact"], s["map"]
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    cfg = ConfigStore().active()
    mode = ("LIVE run, N = 1" if not settings.offline()
            else "OFFLINE replay of ONE recorded live run (tests/fixtures/llm)")
    out = [
        "# coLEX results", "", "Generated by `make eval`. Do not edit by hand.", "",
        f"- Date: {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC · git {sha} · config {cfg.version_id} · map "
        f"{s['map_version']}",
        f"- Model: {cfg.payload['models']['cheap']} (cheap) / {cfg.payload['models']['strong']} (strong)",
        f"- Mode: {mode}", f"- Demo exit code: {exit_code}", "",
        "**How to read this.** One run on one small fabricated company (21 resources, 23 acts). It shows what this run "
        "did, not how often the system is right. The taxonomy, the map rules and the triage prompt were tuned on this "
        "same data. Model output varies between live runs. Human answers were given by the demo auto-clicker.", "",
        "## Triage", "",
        f"- Precision: {pct(t['tp'], t['pred'])} · recall: {pct(t['tp'], t['true'])} (positive = act labelled relevant "
        "in the ground truth)",
        f"- Acts archived with a reason: {t['archived_with_reason']}", "",
        "## Impact items that reached a human", "",
        "An item matches when law, resource and action agree and the line ranges overlap by at least one line.", "",
        f"- Recall: {pct(i['hit_expected'], i['expected'])} · precision: {pct(i['hit_reported'], i['reported'])}",
        f"- Routing: {pct(i['routed'], i['hit_expected'])} of the matched items went to the expected channel",
        f"- Items on resources that must not be flagged: {i['banned']}", "", "Expected but not found:", ""]
    near = {(p["law"], p["resource_uri"], p["action"]) for p in i["extra"]}
    out += [f"- {x['law']} · {x['uri']} · {x['action']}"
            + (" (reported, but the cited lines do not overlap the expected lines "
               f"{x['lines'][0]}-{x['lines'][1]}: counted as a miss)" if (x["law"], x["uri"], x["action"]) in near else "")
            for x in i["missed"]] or ["- none"]
    out += ["", "Reported but not in the ground truth (a human should judge these; some may be legitimate):", ""]
    out += [f"- {p['law']} · {p['resource_uri']}:{p['lines']['start']}-{p['lines']['end']} · {p['action']} · "
            f"{p['citation']} → {p['channel']}" for p in i["extra"]] or ["- none"]
    out += ["", f"## Map quality (against the ground truth, {m['n']} resources)", "",
            f"- Primary path: {pct(m['path'], m['n'])}", f"- Owner: {pct(m['owner'], m['n'])}",
            f"- Counterparty on contracts: {pct(m['counterparty'], m['contracts'])}",
            f"- Ownership source: {m['sources']} · unclassified queue: {m['unclassified']}", "", "## Code changes", ""]
    for c in s["changes"]:
        if c["change"] is None:
            out.append(f"- {c['file']} ({c['law']}): NO change request in this run")
            continue
        ch = c["change"]
        out.append(f"- {c['file']}: change request on `{ch['branch']}` after {ch['iterations']} attempt(s); failing "
                   f"tests {ch['tests_before']['failed']} → {ch['tests_after']['failed']}; decision {c['decision']}; "
                   "merged: no")
    out += ["", "## Per relevant act", "",
            "| Act | Items | Model tokens | Cost when recorded (USD) | Context via map | Baseline A: whole corpus | "
            "Ratio A | Baseline B: touched areas | Ratio B | Depth | Fragments read |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a in s["acts"]:
        if a["summary"] is None:
            out.append(f"| {a['celex']} | run not finished | | | | | | | | | |")
            continue
        r, c = a["summary"], a["summary"].get("context") or {}
        out.append(f"| {a['celex']} | {r['items']} | {r['tokens']} | {a['recorded_cost']:.4f} | "
                   f"{c.get('context_tokens_used')} | {c.get('baseline_a_whole_corpus_tokens')} | {c.get('ratio_vs_a')} "
                   f"| {c.get('baseline_b_touched_areas_tokens')} | {c.get('ratio_vs_b')} | {c.get('navigation_depth')} "
                   f"| {c.get('fragments_read')}/{c.get('fragments_total')} |")
    out += ["", "A ratio above 1 means the agent read MORE through the map than the whole corpus contains. On this "
            "sandbox the map does not save context.", "", "## Not measured", "",
            "- Time: an offline replay takes seconds and says nothing about live speed.",
            "- The manual-triage projection of brief §7: live triage time per document was not measured, and the "
            "study behind the 25,537-documents figure was not verified.",
            "- Repeated live runs (N = 3 with min and max) were not done."]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
